/**
 * Concatenate engine modules into a classic IIFE for DevTools panels.
 * Chrome DevTools panel pages often fail to load ES modules silently.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const files = [
  'src/extract.js',
  'src/extract-selection.js',
  'src/catalog/rich-results.js',
  'src/catalog/deprecations.js',
  'src/catalog/syntax.js',
  'src/rules.js',
  'src/normalize.js',
  'src/validate.js',
  'src/score.js',
  'src/agent.js',
];

function stripModuleSyntax(code) {
  return code
    .replace(/^\s*import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^\s*export\s+\{[^}]*\}\s*;?\s*$/gm, '')
    .replace(/^export\s+async\s+function/gm, 'async function')
    .replace(/^export\s+function/gm, 'function')
    .replace(/^export\s+const /gm, 'const ')
    .replace(/^export\s+let /gm, 'let ')
    .replace(/^export\s+var /gm, 'var ')
    .replace(/^export\s+\{[^}]+\}\s+from\s+['"][^'"]+['"];?\s*$/gm, '');
}

const body = files
  .map((rel) => stripModuleSyntax(readFileSync(join(root, rel), 'utf8')))
  .join('\n\n');

const out = `/* generated by scripts/bundle.mjs — do not edit by hand */
(function (global) {
${body}

global.SchemaDT = {
  extractPageSchema,
  EXTRACT_SOURCE,
  inspectSelectedSchemaNode,
  SELECTION_EXTRACT_SOURCE,
  normalize,
  stripSchemaPrefix,
  validate,
  score,
  buildAgentBundle,
  toAgentMarkdown,
};
})(typeof globalThis !== 'undefined' ? globalThis : window);
`;

const dest = join(root, 'devtools/engine.classic.js');
writeFileSync(dest, out);
console.log('wrote', dest, out.length, 'bytes');
